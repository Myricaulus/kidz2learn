"""Regenerates the file manifests the app loads at runtime from what is actually on disk.

    wwwroot/sids/sidfiles.<hash>.json                    every *.sid in wwwroot/sids, with the length
                                                         of its first subtune in seconds (null if
                                                         unknown) from tools/data/sid-songlengths.md5
    wwwroot/audio/affirmations/affirmations.<hash>.json  {"erfolg": [...], "misserfolg": [...]} audio files

<hash> is the start of the content's SHA-256, so a changed manifest gets a new URL and browsers
may cache every version forever; older versions are deleted. Shared/AssetManifests.g.cs holds the
current URLs for the app (it must stay checked in: MSBuild globs the sources before this script
runs, so a file created here only compiles from the next build on).

Runs before every build (Kidz2Learn.csproj, target RegenerateAudioManifests), locally and on
Netlify, so dropping in a new file and rebuilding is enough. Standard library only. Files are
sorted for a stable diff and only rewritten when their content changes.

    python3 tools/generate_manifests.py
"""

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIDS = ROOT / "wwwroot" / "sids"
AFFIRMATIONS = ROOT / "wwwroot" / "audio" / "affirmations"
WWWROOT = ROOT / "wwwroot"
CSHARP = ROOT / "Shared" / "AssetManifests.g.cs"
SONGLENGTHS = ROOT / "tools" / "data" / "sid-songlengths.md5"
AUDIO_SUFFIXES = {".opus", ".ogg", ".mp3", ".wav", ".m4a", ".webm"}


def names(folder: Path, suffixes: set[str]) -> list[str]:
    if not folder.is_dir():
        return []
    return sorted(
        (f.name for f in folder.iterdir()
         if f.is_file() and not f.name.startswith(".") and f.suffix.lower() in suffixes),
        key=str.casefold,
    )


def name_key(file_name: str) -> str:
    """"Dragon's_Ballad.sid" and HVSC's "Dragons_Ballad.sid" are the same tune."""
    return re.sub(r"[^a-z0-9]", "", file_name.lower())


def seconds(length: str) -> float:
    minutes, rest = length.split(":")
    return round(int(minutes) * 60 + float(rest), 1)


def song_lengths() -> tuple[dict[str, float], dict[str, float]]:
    """First-subtune length in seconds, by MD5 and by file name, from SONGLENGTHS."""
    by_md5, by_name, path = {}, {}, None
    if not SONGLENGTHS.is_file():
        return by_md5, by_name
    for line in SONGLENGTHS.read_text(encoding="utf-8").splitlines():
        if line.startswith("; /"):
            path = line[2:].strip()
        elif "=" in line and not line.startswith(";"):
            md5, lengths = line.split("=", 1)
            first = seconds(lengths.split()[0])
            by_md5[md5.strip()] = first
            if path:
                by_name[name_key(path.rsplit("/", 1)[-1])] = first
            path = None
    return by_md5, by_name


def write_if_changed(path: Path, text: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8-sig") == text:
        return
    path.write_text(text, encoding="utf-8")
    print(f"generate_manifests: updated {path.relative_to(ROOT)}")


def write_hashed(folder: Path, stem: str, data) -> str:
    """Writes <stem>.<hash>.json, deletes other versions, returns its URL relative to wwwroot."""
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    path = folder / f"{stem}.{hashlib.sha256(text.encode()).hexdigest()[:10]}.json"
    for old in [folder / f"{stem}.json", *folder.glob(f"{stem}.*.json")]:
        if old != path and old.exists():
            old.unlink()
            print(f"generate_manifests: removed {old.relative_to(ROOT)}")
    write_if_changed(path, text)
    return path.relative_to(WWWROOT).as_posix()


def main() -> int:
    if not SIDS.is_dir():
        print(f"generate_manifests: error: {SIDS} not found", file=sys.stderr)
        return 1
    sids = names(SIDS, {".sid"})
    if not sids:
        print(f"generate_manifests: error: no .sid files in {SIDS}", file=sys.stderr)
        return 1
    by_md5, by_name = song_lengths()
    catalog = []
    for sid in sids:
        md5 = hashlib.md5((SIDS / sid).read_bytes()).hexdigest()
        catalog.append({"file": sid, "seconds": by_md5.get(md5, by_name.get(name_key(sid)))})
    sid_url = write_hashed(SIDS, "sidfiles", catalog)

    affirmations_url = write_hashed(AFFIRMATIONS, "affirmations", {
        "erfolg": names(AFFIRMATIONS / "erfolg", AUDIO_SUFFIXES),
        "misserfolg": names(AFFIRMATIONS / "misserfolg", AUDIO_SUFFIXES),
    })

    write_if_changed(CSHARP, f"""// <auto-generated>
//   Generated by tools/generate_manifests.py before every build - do not edit by hand.
// </auto-generated>
namespace Kidz2Learn.Shared;

/// <summary>Current URLs of the build-generated manifests; the hash in the name changes with their content.</summary>
public static class AssetManifests
{{
    public const string SidFiles = "{sid_url}";
    public const string Affirmations = "{affirmations_url}";
}}
""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
